import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetRoot = path.join(root, 'public', 'assets');
const groups = {};
const manifest = {};
const labels = { avatars: 'Learner avatars', badges: 'Achievement badges', brand: 'Brand & identity', icons: 'Interface icons', illustrations: 'Illustrations', tracks: 'Learning tracks' };
for (const category of await readdir(assetRoot, { withFileTypes: true })) {
  if (!category.isDirectory()) continue;
  const names = (await readdir(path.join(assetRoot, category.name))).filter(name => name.endsWith('.svg')).sort();
  groups[category.name] = names;
  for (const name of names) manifest[`assets/${category.name}/${name}`] = { type: 'svg', bytes: (await stat(path.join(assetRoot, category.name, name))).size };
}
const count = Object.keys(manifest).length;
await writeFile(path.join(assetRoot, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
// The app renders the editable Material Symbols inline, with no icon font.
const symbolPaths = {};
const viewBoxes = {};
for (const name of groups.icons) {
  const svg = await readFile(path.join(assetRoot, 'icons', name), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] || '0 0 24 24';
  const body = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!body) throw new Error(`Invalid SVG icon: ${name}`);
  symbolPaths[name.replace('.svg', '')] = body;
  viewBoxes[name.replace('.svg', '')] = viewBox;
}
await writeFile(path.join(root, 'src', 'icons.js'), `// Google Material Symbols Rounded, 24px. Apache-2.0.\n// Generated by scripts/refresh-assets.mjs from public/assets/icons/.\nexport const symbols = ${JSON.stringify(symbolPaths, null, 2)};\nexport const viewBoxes = ${JSON.stringify(viewBoxes, null, 2)};\n\nexport function icon(name, slot = '') {\n  const key = Object.hasOwn(symbols, name) ? name : 'help';\n  return \`<svg class="icon icon-\${key}" \${slot ? \`slot="\${slot}"\` : ''} viewBox="\${viewBoxes[key]}" fill="currentColor" aria-hidden="true" focusable="false">\${symbols[key]}</svg>\`;\n}\n`);
const cards = Object.entries(groups).map(([category, names]) => `<section id="${category}" class="asset-section"><div class="gallery-section-heading"><h2>${labels[category] || category}</h2><span>${names.length} assets</span></div><div class="asset-grid">${names.map(name => `<article class="asset card" data-search="${category} ${name.replaceAll('-', ' ')}"><a class="asset-preview ${/white|dark/.test(name) ? 'dark-preview' : ''}" href="public/assets/${category}/${name}" target="_blank" rel="noopener"><img loading="lazy" src="public/assets/${category}/${name}" alt="${name.replace('.svg', '').replaceAll('-', ' ')}" width="180" height="135"></a><div class="asset-details"><h3>${name}</h3><a href="public/assets/${category}/${name}" download>Download SVG <span aria-hidden="true">↗</span></a></div></article>`).join('\n')}</div></section>`).join('\n');
const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Editable Asset Library · GDGoC Learn</title>
  <link rel="icon" href="public/assets/brand/gdgoc-favicon.svg" type="image/svg+xml">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Google+Sans:wght@400;500;600;700&display=swap">
  <link rel="stylesheet" href="src/styles.css">
  <link rel="stylesheet" href="src/google.css">
  <link rel="stylesheet" href="src/gallery.css">
  <script type="importmap">{"imports":{"@material/web/":"https://esm.run/@material/web@2.4.1/"}}</script>
  <script type="module">import '@material/web/all.js';</script>
</head>
<body class="gallery-page">
  <a class="skip-link" href="#gallery-content">Skip to assets</a>
  <header class="gallery-header"><a href="./index.html#/dashboard"><img src="public/assets/brand/gdgoc-learn-lockup.svg" alt="GDGoC · AAST Aswan" width="208" height="60"></a><a class="gallery-app-link" href="./index.html#/dashboard">Open learning portal <span aria-hidden="true">↗</span></a></header>
  <main id="gallery-content" class="gallery-main">
    <div class="gallery-intro"><div><span class="eyebrow">THE LITTLE DETAILS THAT MAKE IT OURS</span><h1>Your community. In every pixel.</h1><p>${count} editable SVG assets for the GDGoC Learn experience.</p></div><span class="gallery-vector-pill">100% editable vectors</span></div>
    <div class="gallery-toolbar"><md-outlined-text-field id="filter" type="search" label="Search the asset library" placeholder="Try certificate, code, or badge" aria-label="Search assets"></md-outlined-text-field><span id="asset-count" role="status">${count} assets</span></div>
    <nav class="gallery-categories" aria-label="Asset categories">${Object.keys(groups).map(category => `<a href="#${category}">${labels[category]}</a>`).join('')}</nav>
    <div id="gallery-sections">${cards}</div>
    <div id="gallery-empty" class="card empty-state" hidden><h2>No matching assets</h2><p>Try a different name or category.</p></div>
    <div class="gallery-footnote"><p>Open any SVG in Figma, Illustrator, Inkscape, or a text editor. Branding comes from the supplied GDGoC_LogoPack. See <a href="public/assets/brand/LOGO-PACK-README.md">the logo kit notes</a> and <a href="docs/06-asset-inventory.md">the asset inventory</a>.</p><a href="screenshots/original-concept-reference.png" target="_blank" rel="noopener">View original design reference ↗</a></div>
  </main>
  <script>
    const field = document.querySelector('#filter');
    field.addEventListener('input', () => {
      const query = field.value.toLowerCase().trim().replaceAll('-', ' ');
      let count = 0;
      document.querySelectorAll('.asset').forEach(asset => { asset.hidden = !asset.dataset.search.includes(query); if (!asset.hidden) count++; });
      document.querySelectorAll('.asset-section').forEach(section => { section.hidden = !section.querySelector('.asset:not([hidden])'); });
      document.querySelector('#asset-count').textContent = count + (count === 1 ? ' asset' : ' assets');
      document.querySelector('#gallery-empty').hidden = count !== 0;
    });
  </script>
</body>
</html>\n`;
await writeFile(path.join(root, 'assets-gallery.html'), html);
console.log(`Refreshed the Material Web gallery and manifest for ${count} editable SVG assets.`);
